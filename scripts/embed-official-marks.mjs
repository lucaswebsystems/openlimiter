/**
 * Embed the 2.1 providers' official marks in the shared row, unmodified.
 *
 *   node scripts/embed-official-marks.mjs
 *
 * Each vendor file in packages/ui/src/marks becomes one data URI in
 * packages/ui/src/marks/official.ts, byte for byte, so every surface draws the
 * vendor's own file as an image without serving it: an image keeps the file's
 * own styles and ids to itself. A provider lane never runs this; the
 * integration owner does, only if a mark file itself ever changes, and
 * packages/ui/test/provider-marks.test.ts fails until then.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const MARKS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "packages", "ui", "src", "marks");
const FILES = {
  SYNTHETIC: "synthetic.svg",
  ZAI: "zai.svg",
  MINIMAX: "minimax.svg",
  CLINE: "cline.svg",
  AUGMENT: "augment.svg",
  AMP: "amp.svg",
  KILO: "kilo.svg",
  COPILOT: "copilot.svg"
};

const entries = Object.entries(FILES).map(([code, file]) =>
  `  ${code}: "data:image/svg+xml;base64,${readFileSync(path.join(MARKS, file)).toString("base64")}"`);
writeFileSync(path.join(MARKS, "official.ts"), [
  "/**",
  " * Generated by scripts/embed-official-marks.mjs. Do not edit.",
  " *",
  " * The 2.1 providers' official marks, each the vendor's own file byte for",
  " * byte as a data URI. Sources and digests: LICENSES.md in this folder.",
  " */",
  "export const OFFICIAL_MARKS = {",
  entries.join(",\n"),
  "} as const;",
  ""
].join("\n"));
process.stdout.write("Embedded " + entries.length + " official marks.\n");
